  function getLang() {
    if (typeof window === "undefined") return "en";
    return window.__lang || localStorage.getItem("__lang") || "en";
  }

  function t(key) {
    const lang = getLang();
    return (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  }

  // Template variable interpolation. Pass `tWith("foo.bar", { name: "Jarron" })`
  // and any `{{name}}` token in the string gets replaced. Used by auth pages
  // that bake the submitted email into a confirmation message.
  function tWith(key, vars) {
    let s = t(key);
    if (vars && typeof s === "string") {
      Object.keys(vars).forEach((k) => {
        s = s.split("{{" + k + "}}").join(String(vars[k] == null ? "" : vars[k]));
      });
    }
    return s;
  }

  function setLang(lang) {
    if (!["en", "es", "zh"].includes(lang)) return;
    window.__lang = lang;
    try { localStorage.setItem("__lang", lang); } catch (e) {}
    document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
    window.dispatchEvent(new CustomEvent("__lang_changed", { detail: { lang } }));
  }

  // Initialize lang on load (so persistence works on refresh)
  if (typeof window !== "undefined") {
    const initial = getLang();
    window.__lang = initial;
    if (typeof document !== "undefined" && document.documentElement) {
      document.documentElement.lang = initial === "zh" ? "zh-Hans" : initial;
    }
  }

